const names = new Intl.DisplayNames(undefined, { type: 'language' });

/** The name of a language tag, as the viewer reads it, or the tag itself when it has none. */
export function languageName(code: string): string {
	try {
		return names.of(code) ?? code;
	} catch {
		return code;
	}
}

/** Every language as a select option, named and sorted by name. */
export function languageOptions(): { code: string; name: string }[] {
	return LANGUAGE_CODES.map((code) => ({ code, name: languageName(code) })).sort((a, b) =>
		a.name.localeCompare(b.name)
	);
}
